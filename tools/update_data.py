"""Refresh gamedata.js (Pokémon, movesets and raid move stats used by Boss Lookup).

Run from anywhere:   python tools/update_data.py

It downloads the latest data, rebuilds gamedata.js, and if anything changed bumps the
cache version in sw.js so installed copies of the app pick up the new data.
Then commit and push as usual.

Sources:
  Pokémon list, GO base stats, movesets: PvPoke gamemaster (github.com/pvpoke/pvpoke)
  Raid (PvE) move power / duration / energy: PokeMiners game master (github.com/PokeMiners/game_masters)
"""
import json, re, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "gamedata.js"
SW = ROOT / "sw.js"
PVPOKE_URL = "https://raw.githubusercontent.com/pvpoke/pvpoke/master/src/data/gamemaster.json"
GM_URL = "https://raw.githubusercontent.com/PokeMiners/game_masters/master/latest/latest.json"

TYPES = ["normal","fire","water","electric","grass","ice","fighting","poison","ground",
         "flying","psychic","bug","rock","ghost","dragon","dark","steel","fairy"]
# PvPoke move ids whose game master name differs
ALIAS = {"PYRO_BALL": "PYROBALL", "TECHNO_BLAST_DOUSE": "TECHNO_BLAST_WATER"}


def fetch_json(url):
    print("Downloading", url)
    req = urllib.request.Request(url, headers={"User-Agent": "go-tools-data-update"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)


def build(pv, gm):
    # PvE move stats keyed by the name in the template id, e.g. V0013_MOVE_WRAP -> WRAP
    pve = {}
    for x in gm:
        s = x.get("data", {}).get("moveSettings")
        if not s:
            continue
        name = re.sub(r"^V\d+_MOVE_", "", x["templateId"])
        rec = (s.get("power", 0), s["durationMs"], s.get("energyDelta", 0))
        pve[name] = rec
        pve.setdefault(name.removesuffix("_FAST"), rec)

    pvmoves = {m["moveId"]: m for m in pv["moves"]}
    move_ids, moves_out, skipped = {}, [], set()

    def move_index(mid):
        if mid in move_ids:
            return move_ids[mid]
        m = pvmoves.get(mid)
        key = "HIDDEN_POWER_FAST" if mid.startswith("HIDDEN_POWER_") else ALIAS.get(mid, mid)
        rec = pve.get(key)
        if not m or not rec or m["type"] not in TYPES:
            skipped.add(mid)               # PvP-only variant, or no raid data yet
            return None
        power, dur, energy = rec
        move_ids[mid] = len(moves_out)
        moves_out.append([m["name"], TYPES.index(m["type"]), power, dur, energy])
        return move_ids[mid]

    def idxs(lst):
        return [i for i in (move_index(mid) for mid in lst) if i is not None]

    mons = []
    for p in pv["pokemon"]:
        tags = p.get("tags", [])
        if "teambuilderexclude" in tags or "duplicate" in p["speciesId"]:
            continue
        flags = (1 if "shadow" in tags else 0) | (2 if "mega" in tags else 0) | (4 if p.get("released") else 0)
        s = p["baseStats"]
        mons.append([p["speciesName"], p["dex"], [TYPES.index(t) for t in p["types"] if t in TYPES],
                     s["atk"], s["def"], s["hp"],
                     idxs(p.get("fastMoves", [])), idxs(p.get("chargedMoves", [])), idxs(p.get("eliteMoves", [])),
                     flags])

    cpm = next(x["data"]["playerLevel"]["cpMultiplier"] for x in gm if "playerLevel" in x.get("data", {}))[:55]

    js = ("// Generated by tools/update_data.py. Do not edit by hand.\n"
          "// Pokémon/movesets: PvPoke gamemaster (github.com/pvpoke/pvpoke).\n"
          "// Raid move stats: PokeMiners game master (github.com/PokeMiners/game_masters).\n"
          "// MOVES: [name, typeIndex, power, durationMs, energy]   (energy < 0 = charged move cost)\n"
          "// MONS:  [name, dex, [types], atk, def, hp, [fast], [charged], [elite], flags 1=shadow 2=mega 4=released]\n"
          "// CPM: combat power multiplier for whole levels 1, 2, 3... (half levels are derived)\n"
          "const CPM = " + json.dumps(cpm) + ";\n"
          "const MOVES = " + json.dumps(moves_out, ensure_ascii=False, separators=(",", ":")) + ";\n"
          "const MONS = " + json.dumps(mons, ensure_ascii=False, separators=(",", ":")).replace('],["', '],\n["') + ";\n")
    return js, len(mons), len(moves_out), skipped


def bump_cache_version():
    text = SW.read_text(encoding="utf-8")
    m = re.search(r'const VERSION = "v(\d+)";', text)
    if not m:
        print("Could not find VERSION in sw.js; bump it by hand.")
        return
    new = int(m.group(1)) + 1
    SW.write_text(text.replace(m.group(0), f'const VERSION = "v{new}";'), encoding="utf-8")
    print(f"sw.js cache version -> v{new}")


def main():
    pv, gm = fetch_json(PVPOKE_URL), fetch_json(GM_URL)
    js, n_mons, n_moves, skipped = build(pv, gm)
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    strip = lambda s: "\n".join(l for l in s.splitlines() if not l.startswith("//"))
    print(f"{n_mons} Pokemon, {n_moves} moves.")
    if skipped:
        print("Moves left out (no raid data):", ", ".join(sorted(skipped)))
    if strip(old) == strip(js):
        print("No changes: gamedata.js is already up to date.")
        return
    OUT.write_text(js, encoding="utf-8")
    print("Updated", OUT.name)
    bump_cache_version()
    print("Now commit and push to publish.")


if __name__ == "__main__":
    main()
